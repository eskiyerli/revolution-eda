def _format_spice_device(dev: DeviceInstance) -> str:
    """Format a device instance as a SPICE subcircuit call.

    SPICE convention: XI0 node1 node2 ... model_name param=val param=val
    """
    # Build terminal node list in a deterministic order
    # Standard MOSFET order: D G S B
    terminal_order = _get_terminal_order(dev.model)
    nodes = []
    for term in terminal_order:
        if term in dev.terminals:
            nodes.append(_sanitize_node(dev.terminals[term]))
    # Any remaining terminals not in the standard order
    for term, node in dev.terminals.items():
        if term not in terminal_order:
            nodes.append(_sanitize_node(node))

    nodes_str = " ".join(nodes)
    params_str = " ".join(f"{k}={_format_param(v)}" for k, v in dev.params.items())

    prefix = "X" if not dev.name.startswith("X") else ""
    line = f"{prefix}{dev.name} {nodes_str} {dev.model}"
    if params_str:
        line += f" {params_str}"
    return line


def _format_spectre_device(dev: DeviceInstance) -> str:
    """Format a device instance in Spectre syntax.

    Spectre convention: I0 (node1 node2 ...) model_name param=val
    """
    terminal_order = _get_terminal_order(dev.model)
    nodes = []
    for term in terminal_order:
        if term in dev.terminals:
            nodes.append(_sanitize_node(dev.terminals[term]))
    for term, node in dev.terminals.items():
        if term not in terminal_order:
            nodes.append(_sanitize_node(node))

    nodes_str = " ".join(nodes)
    params_str = " ".join(f"{k}={_format_param(v)}" for k, v in dev.params.items())

    line = f"{dev.name} ({nodes_str}) {dev.model}"
    if params_str:
        line += f" {params_str}"
    return line


def _format_vacask_device(dev: DeviceInstance) -> str:
    """Format a device instance in VACASK syntax.

    VACASK convention: name (node1 node2 ...) model_name param=val
    Same as Spectre but instance names are lowercase by convention.
    """
    terminal_order = _get_terminal_order(dev.model)
    nodes = []
    for term in terminal_order:
        if term in dev.terminals:
            nodes.append(_sanitize_node(dev.terminals[term]))
    for term, node in dev.terminals.items():
        if term not in terminal_order:
            nodes.append(_sanitize_node(node))

    nodes_str = " ".join(nodes)
    params_str = " ".join(f"{k}={_format_param(v)}" for k, v in dev.params.items())

    name = dev.name.lower()
    line = f"{name} ({nodes_str}) {dev.model}"
    if params_str:
        line += f" {params_str}"
    return line


def _get_terminal_order(model: str) -> list[str]:
    """Get standard terminal order for a device model."""
    model_lower = model.lower()
    if "nmos" in model_lower or "pmos" in model_lower or "fet" in model_lower:
        return ["D", "G", "S", "B"]
    elif "npn" in model_lower or "pnp" in model_lower:
        return ["C", "B", "E"]
    elif "cap" in model_lower or "mimcap" in model_lower:
        return ["PLUS", "MINUS"]
    elif "res" in model_lower or "rppd" in model_lower or "rhigh" in model_lower:
        return ["PLUS", "MINUS", "B"]
    elif "diode" in model_lower:
        return ["A", "C"]
    else:
        return []


def _format_param(value) -> str:
    """Format a parameter value for netlist output."""
    if isinstance(value, float):
        if abs(value) < 1e-12:
            return "0"
        elif abs(value) < 1e-6:
            return f"{value * 1e9:.4g}n"
        elif abs(value) < 1e-3:
            return f"{value * 1e6:.4g}u"
        elif abs(value) < 1:
            return f"{value * 1e3:.4g}m"
        else:
            return f"{value:.4g}"
    return str(value)


def _sanitize_node(name: str) -> str:
    """Sanitize a node name for netlist output."""
    return name.replace(":", "_").replace(" ", "_").replace("/", "_")


def _spef_node(name: str, node_map: dict[str, int]) -> str:
    """Get SPEF node reference."""
    if name in node_map:
        return f"*{node_map[name]}"
    return _sanitize_node(name)


def get_writer(format_name: str) -> NetlistWriter:
    """Get a netlist writer by format name.

    Args:
        format_name: One of "spice", "spef", "spectre", "vacask".

    Returns:
        Appropriate NetlistWriter instance.
    """
    writers = {
        "spice": SpiceWriter,
        "spef": SpefWriter,
        "spectre": SpectreWriter,
        "vacask": VacaskWriter,
    }
    if format_name not in writers:
        raise ValueError(f"Unknown format '{format_name}'. Available: {list(writers.keys())}")
    return writers[format_name]()
